/**
 * All encryption happens client-side. The key never leaves this module's
 * caller, and every block encryption performed through this module under one
 * generated key receives a unique 96-bit nonce.
 */

import type { EncryptedBlock } from '../server/oram-server.js';

export type { EncryptedBlock };

export interface ClientKey {
  readonly cryptoKey: CryptoKey;
}

export const BLOCK_ID_SIZE = 4;
export const BLOCK_DATA_SIZE = 32;
export const GCM_NONCE_SIZE = 12;
export const PLAINTEXT_SIZE = BLOCK_ID_SIZE + BLOCK_DATA_SIZE;
export const ENCRYPTED_BLOCK_SIZE = PLAINTEXT_SIZE + 16; // 128-bit GCM tag

const DUMMY_BLOCK_ID = 0xffffffff;
const MAX_REAL_BLOCK_ID = DUMMY_BLOCK_ID - 1;

interface NonceState {
  prefix: Uint8Array<ArrayBuffer>;
  counter: number;
}

// Keeping nonce state outside ClientKey prevents callers from rewinding this
// module's counter or mutating its random prefix. The 64-bit random prefix is
// scoped to one newly generated AES key; the 32-bit counter guarantees no reuse
// among calls through this module until the explicit exhaustion error. ClientKey
// still exposes the non-extractable CryptoKey to trusted client code, so this is
// not a misuse-resistant boundary against arbitrary same-origin code.
const nonceStates = new WeakMap<CryptoKey, NonceState>();

export class BlockAuthenticationError extends Error {
  constructor(message = 'Encrypted block failed AES-GCM authentication.') {
    super(message);
    this.name = 'BlockAuthenticationError';
  }
}

function nonceState(key: ClientKey): NonceState {
  if (!key || !(key.cryptoKey instanceof CryptoKey)) {
    throw new TypeError('A valid generated client key is required.');
  }
  const state = nonceStates.get(key.cryptoKey);
  if (!state) throw new TypeError('Client key was not generated by generateClientKey().');
  return state;
}

function nextNonce(key: ClientKey): Uint8Array<ArrayBuffer> {
  const state = nonceState(key);
  if (state.counter > 0xffffffff) {
    throw new Error('AES-GCM nonce space exhausted for this client key.');
  }
  const nonce = new Uint8Array(GCM_NONCE_SIZE);
  nonce.set(state.prefix, 0);
  new DataView(nonce.buffer).setUint32(8, state.counter, false);
  state.counter += 1;
  return nonce;
}

function assertRealBlockId(blockId: number): void {
  if (!Number.isSafeInteger(blockId) || blockId < 0 || blockId > MAX_REAL_BLOCK_ID) {
    throw new RangeError(`blockId must be an integer in [0, ${MAX_REAL_BLOCK_ID}].`);
  }
}

/** Copy and zero-pad a demo block without silently truncating caller data. */
export function normalizeBlockData(data: Uint8Array): Uint8Array {
  if (!(data instanceof Uint8Array)) throw new TypeError('Block data must be a Uint8Array.');
  if (data.length > BLOCK_DATA_SIZE) {
    throw new RangeError(`Block data must be at most ${BLOCK_DATA_SIZE} bytes.`);
  }
  const normalized = new Uint8Array(BLOCK_DATA_SIZE);
  normalized.set(data);
  return normalized;
}

function assertEncryptedBlock(encrypted: EncryptedBlock): void {
  if (!encrypted || !(encrypted.ciphertext instanceof Uint8Array)) {
    throw new BlockAuthenticationError('Encrypted block ciphertext must be a Uint8Array.');
  }
  if (!(encrypted.nonce instanceof Uint8Array)) {
    throw new BlockAuthenticationError('Encrypted block nonce must be a Uint8Array.');
  }
  if (encrypted.nonce.length !== GCM_NONCE_SIZE) {
    throw new BlockAuthenticationError(
      `Encrypted block nonce must be exactly ${GCM_NONCE_SIZE} bytes.`,
    );
  }
  if (encrypted.ciphertext.length !== ENCRYPTED_BLOCK_SIZE) {
    throw new BlockAuthenticationError(
      `Encrypted block ciphertext must be exactly ${ENCRYPTED_BLOCK_SIZE} bytes.`,
    );
  }
}

/** Generate a non-extractable 256-bit AES-GCM key and private nonce state. */
export async function generateClientKey(): Promise<ClientKey> {
  const cryptoKey = await crypto.subtle.generateKey(
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
  const prefix = new Uint8Array(8);
  crypto.getRandomValues(prefix);
  nonceStates.set(cryptoKey, { prefix, counter: 0 });
  return { cryptoKey };
}

/** Encrypt a block id and at most 32 bytes of data with AES-256-GCM. */
export async function encryptBlock(
  blockId: number,
  data: Uint8Array,
  key: ClientKey,
): Promise<EncryptedBlock> {
  assertRealBlockId(blockId);
  const normalized = normalizeBlockData(data);
  const nonce = nextNonce(key);

  const plaintext = new Uint8Array(PLAINTEXT_SIZE);
  new DataView(plaintext.buffer).setUint32(0, blockId, false);
  plaintext.set(normalized, BLOCK_ID_SIZE);

  const ciphertext = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv: nonce },
    key.cryptoKey,
    plaintext,
  );
  return { ciphertext: new Uint8Array(ciphertext), nonce };
}

/**
 * Decrypt a fixed-size block. A valid encrypted dummy returns null; malformed
 * input, a wrong key, or a failed GCM tag throws instead of being mistaken for
 * padding and silently turning missing data into zeroes.
 */
export async function decryptBlock(
  encrypted: EncryptedBlock,
  key: ClientKey,
): Promise<{ blockId: number; data: Uint8Array } | null> {
  assertEncryptedBlock(encrypted);
  nonceState(key);

  let plaintextBuffer: ArrayBuffer;
  try {
    plaintextBuffer = await crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: new Uint8Array(encrypted.nonce) },
      key.cryptoKey,
      new Uint8Array(encrypted.ciphertext),
    );
  } catch {
    throw new BlockAuthenticationError();
  }

  const plaintext = new Uint8Array(plaintextBuffer);
  if (plaintext.length !== PLAINTEXT_SIZE) {
    throw new BlockAuthenticationError(
      `Authenticated plaintext must be exactly ${PLAINTEXT_SIZE} bytes.`,
    );
  }
  const blockId = new DataView(plaintext.buffer, plaintext.byteOffset, plaintext.byteLength)
    .getUint32(0, false);
  if (blockId === DUMMY_BLOCK_ID) return null;
  return {
    blockId,
    data: plaintext.slice(BLOCK_ID_SIZE, BLOCK_ID_SIZE + BLOCK_DATA_SIZE),
  };
}

/** Create a fixed-size encrypted dummy indistinguishable from a real block. */
export async function createDummyBlock(key: ClientKey): Promise<EncryptedBlock> {
  const nonce = nextNonce(key);
  const plaintext = new Uint8Array(PLAINTEXT_SIZE);
  new DataView(plaintext.buffer).setUint32(0, DUMMY_BLOCK_ID, false);
  const ciphertext = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv: nonce },
    key.cryptoKey,
    plaintext,
  );
  return { ciphertext: new Uint8Array(ciphertext), nonce };
}

/** Re-encrypt a plaintext block under the next unique nonce for this key. */
export async function refreshEncryption(
  block: { blockId: number; data: Uint8Array },
  key: ClientKey,
): Promise<EncryptedBlock> {
  return encryptBlock(block.blockId, block.data, key);
}
